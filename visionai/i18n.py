def label(name: str, lang: str) -> str:
    """Translate a detector class name, falling back to English."""
    if lang in LANG_ORDER and name in LABELS:
        return LABELS[name][LANG_ORDER.index(lang)]
    return name


def phrase(key: str, lang: str, **kwargs) -> str | None:
    """A phrase in `lang`, or None for English (English sentences are built separately)."""
    table = PHRASES.get(lang)
    if table is None:
        return None
    return table[key].format(**kwargs)
